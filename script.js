/* =========================================================
   DeepSeek Usage Monitor — landing scripts
   ========================================================= */
(function () {
  'use strict';

  /* ---------- Sticky nav shadow ---------- */
  var navbar = document.getElementById('navbar');
  var goToTop = document.getElementById('goToTop');

  function onScroll() {
    var y = window.scrollY || window.pageYOffset;
    navbar.classList.toggle('scrolled', y > 8);
    goToTop.classList.toggle('visible', y > 600);
  }
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  /* ---------- Mobile menu ---------- */
  var toggle = document.getElementById('mobileToggle');
  var navLinks = document.getElementById('navLinks');

  function closeMenu() {
    navLinks.classList.remove('open');
    toggle.classList.remove('open');
    toggle.setAttribute('aria-expanded', 'false');
  }

  toggle.addEventListener('click', function () {
    var open = navLinks.classList.toggle('open');
    toggle.classList.toggle('open', open);
    toggle.setAttribute('aria-expanded', String(open));
  });

  navLinks.addEventListener('click', function (e) {
    if (e.target.closest('a')) closeMenu();
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') {
      closeMenu();
      closeLang();
    }
  });

  /* ---------- Language switcher ---------- */
  var langSwitch = document.getElementById('langSwitch');
  var langBtn = langSwitch ? langSwitch.querySelector('.lang-btn') : null;

  function closeLang() {
    if (!langSwitch) return;
    langSwitch.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  }

  if (langSwitch && langBtn) {
    langBtn.addEventListener('click', function (e) {
      e.stopPropagation();
      var open = langSwitch.classList.toggle('open');
      langBtn.setAttribute('aria-expanded', String(open));
    });

    document.addEventListener('click', function (e) {
      if (!langSwitch.contains(e.target)) closeLang();
    });
  }

  /* ---------- Standalone fallback (opened from disk, not from a translator) ----------
     The language links point at /<locale>/ folders built by scripts/build-i18n.js.
     Without a web server they do not exist, so stay on the page instead of 404ing. */
  if (location.protocol === 'file:' && langSwitch) {
    langSwitch.querySelectorAll('.lang-menu a').forEach(function (a) {
      if (a.classList.contains('active')) return;
      a.addEventListener('click', function (e) {
        e.preventDefault();
        closeLang();
        var msg = document.createElement('div');
        msg.className = 'lang-toast';
        msg.textContent = 'Localized pages are generated by `node scripts/build-i18n.js` and need a web server (npx serve .).';
        document.body.appendChild(msg);
        setTimeout(function () { msg.remove(); }, 4000);
      });
    });
  }

  /* ---------- Go to top ---------- */
  goToTop.addEventListener('click', function () {
    window.scrollTo({ top: 0, behavior: 'smooth' });
  });

  /* ---------- Reveal on scroll ---------- */
  var targets = document.querySelectorAll(
    '.feature-card, .step, .shot, .budget-card, .privacy-item, .section-head, .privacy-box, .faq'
  );

  if ('IntersectionObserver' in window &&
      !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    targets.forEach(function (el) { el.classList.add('reveal'); });

    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (!entry.isIntersecting) return;
        var el = entry.target;
        var siblings = Array.prototype.slice.call(el.parentElement.children);
        var index = Math.max(0, siblings.indexOf(el));
        el.style.transitionDelay = Math.min(index * 60, 300) + 'ms';
        el.classList.add('in');
        io.unobserve(el);
      });
    }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

    targets.forEach(function (el) { io.observe(el); });
  }

  /* ---------- Budget bars: animate to width ---------- */
  var bars = document.querySelectorAll('.bar-fill');
  if ('IntersectionObserver' in window) {
    var barIO = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (!entry.isIntersecting) return;
        var bar = entry.target;
        var target = bar.style.width;
        bar.style.width = '0';
        requestAnimationFrame(function () {
          setTimeout(function () { bar.style.width = target; }, 80);
        });
        barIO.unobserve(bar);
      });
    }, { threshold: 0.4 });
    bars.forEach(function (bar) { barIO.observe(bar); });
  }

  /* ---------- Footer year ---------- */
  var year = document.getElementById('year');
  if (year) year.textContent = String(new Date().getFullYear());
})();
